BEFORE UPDATE ON artists
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER set_timestamp_music_directors
BEFORE UPDATE ON music_directors
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER set_timestamp_user_playlists
BEFORE UPDATE ON user_playlists
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();
